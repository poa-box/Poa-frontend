import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { Writable } from 'node:stream';
import { writeToStream } from '@zk-email/helpers/dist/lib/mailauth/tools';
import { buildCircuitInputHints } from '@poa-box/core/email/proof';
import { rawEmailBytes, readRawEmail } from '@/lib/zkemail/rawEmail';
import {
  CLAIM_INBOX_ADDRESS, CLAIM_INBOX_ORIGIN, CLAIM_INBOX_MAX_BYTES, CLAIM_INBOX_TTL_SECONDS,
  buildClaimInboxEmail, createClaimInboxFixture, inboxBytesToString, inboxStringToBytes,
} from '@/test/zkemail/claimInboxFixture';

let fixture;
let outbound;
const pathFor = address => `/claim-email?claimer=${encodeURIComponent(address)}`;
const command = `Claim POP role for ${CLAIM_INBOX_ADDRESS}`;

beforeEach(() => {
  fixture = createClaimInboxFixture();
  outbound = vi.fn(() => { throw new Error('Network forbidden in inbox simulation.'); });
  vi.stubGlobal('fetch', outbound);
});
afterEach(() => {
  expect(outbound).not.toHaveBeenCalled();
  for (const { state } of fixture.deliveries) {
    expect(state.forwards).toEqual([]);
    expect(state.replies).toEqual([]);
  }
  vi.unstubAllGlobals();
});

describe('actual claim inbox email -> KV -> fetch handlers', () => {
  it('moves from pending 404 to ready 200 with the exact delivered MIME and scoped key', async () => {
    const pending = await fixture.fetch();
    expect(pending.status).toBe(404);
    expect(await pending.json()).toEqual({ status: 'pending' });
    const raw = buildClaimInboxEmail();
    const { message, state } = await fixture.deliver({ raw, chunkSize: 17 });
    expect(state.rejections).toEqual([]);
    expect(message.raw.locked).toBe(false);
    expect(fixture.kv.calls.put).toEqual([{
      key: `claim:${CLAIM_INBOX_ADDRESS.toLowerCase()}`,
      value: inboxBytesToString(raw), options: { expirationTtl: CLAIM_INBOX_TTL_SECONDS },
    }]);
    const ready = await fixture.fetch(pathFor(CLAIM_INBOX_ADDRESS.toUpperCase()));
    expect(ready.status).toBe(200);
    expect(ready.headers.get('Content-Type')).toBe('application/json');
    expect(await ready.json()).toEqual({ status: 'ready', eml: inboxBytesToString(raw) });
    expect((await fixture.fetch(pathFor(`0x${'22'.repeat(20)}`))).status).toBe(404);
  });

  it('provides reusable browser-intercept responses generated by the actual handlers', async () => {
    expect(await fixture.responseFor()).toMatchObject({ status: 404, body: '{"status":"pending"}' });
    await fixture.deliver();
    const fulfilled = await fixture.responseFor();
    expect(fulfilled.status).toBe(200);
    expect(JSON.parse(fulfilled.body).eml).toBe(inboxBytesToString(buildClaimInboxEmail()));
  });

  it('keeps the latest accepted mail per address and does not replace it with rejected mail', async () => {
    await fixture.deliver({ raw: buildClaimInboxEmail({ body: 'First\r\n' }) });
    fixture.kv.advanceMs(1000);
    const second = buildClaimInboxEmail({ body: 'Second\r\n' });
    await fixture.deliver({ raw: second });
    await fixture.deliver({ raw: buildClaimInboxEmail({ dkim: null }) });
    expect(fixture.kv.calls.put).toHaveLength(2);
    expect((await (await fixture.fetch()).json()).eml).toBe(inboxBytesToString(second));
  });

  it('expires exactly one hour after the most recent successful delivery', async () => {
    await fixture.deliver();
    fixture.kv.advanceMs(3599_000);
    expect((await fixture.fetch()).status).toBe(200);
    await fixture.deliver({ raw: buildClaimInboxEmail({ body: 'Replacement\r\n' }) });
    fixture.kv.advanceMs(3599_000);
    expect((await fixture.fetch()).status).toBe(200);
    fixture.kv.advanceMs(1000);
    expect(await (await fixture.fetch()).json()).toEqual({ status: 'pending' });
    expect((await fixture.fetch()).status).toBe(404);
  });
});

describe('raw signed-byte transport, independent of cryptographic verification', () => {
  it.each([1, 31, 16384])('preserves every octet through chunk size %i, KV and HTTP JSON', async chunkSize => {
    const octets = Uint8Array.from({ length: 256 }, (_, byte) => byte);
    const raw = buildClaimInboxEmail({
      extraHeaders: [`X-Synthetic-Signed-Bytes: ${inboxBytesToString(Uint8Array.of(0x80, 0x91, 0x9f, 0xe9, 0xff))}`],
      body: inboxBytesToString(octets),
    });
    const { state } = await fixture.deliver({ raw, chunkSize });
    expect(state.rejections).toEqual([]);
    const response = await fixture.fetch();
    // Response.json() crosses actual UTF-8 JSON serialization/parsing; each eml code unit is a byte.
    const { eml } = await response.json();
    expect([...eml].every(character => character.charCodeAt(0) <= 255)).toBe(true);
    expect(inboxStringToBytes(eml)).toEqual(raw);
    expect(rawEmailBytes(eml)).toEqual(raw);
    expect(inboxStringToBytes(eml).slice(-256)).toEqual(octets);
  });

  it('preserves UTF-8 source octets without decoding/re-encoding the signed header', async () => {
    const utf8Name = Uint8Array.of(0xc3, 0xa9, 0xe2, 0x80, 0x99);
    const raw = buildClaimInboxEmail({ extraHeaders: [`X-Synthetic-Signed-Name: ${inboxBytesToString(utf8Name)}`] });
    await fixture.deliver({ raw });
    const { eml } = await (await fixture.fetch()).json();
    expect(inboxStringToBytes(eml)).toEqual(raw);
    // Demonstrate why the frontend must supply byte input to its DKIM helper, not UTF-8 of eml.
    expect(new TextEncoder().encode(eml)).not.toEqual(raw);
  });

  it('roundtrips JSON bytes through the installed frontend DKIM helper stream transport', async () => {
    const raw = buildClaimInboxEmail({ body: inboxBytesToString(Uint8Array.from({ length: 256 }, (_, byte) => byte)) });
    await fixture.deliver({ raw });
    const { eml } = await (await fixture.fetch()).json();
    const capture = async input => {
      const chunks = [];
      const sink = new Writable({ write(chunk, encoding, done) { chunks.push(chunk); done(); } });
      await writeToStream(sink, input);
      return new Uint8Array(Buffer.concat(chunks));
    };
    // This is the actual installed helper transport, without DNS or signature/proof verification.
    expect(await capture(rawEmailBytes(eml))).toEqual(raw);
    // Passing a binary string directly would UTF-8-transcode the signed bytes.
    expect(await capture(eml)).not.toEqual(raw);
    const manual = await readRawEmail({ arrayBuffer: async () => raw.buffer });
    expect(rawEmailBytes(manual)).toEqual(rawEmailBytes(eml));
  });

  it('makes the test helper reject Unicode text accidentally substituted for raw bytes', () => {
    expect(() => inboxStringToBytes('\u20ac')).toThrow('byte-valued');
  });
});

describe('subject routing and DKIM presence', () => {
  const encodedB = text => `=?UTF-8?B?${btoa(text)}?=`;
  const encodedQ = text => `=?UTF-8?Q?${text.replace(/ /g, '_')}?=`;
  it.each([
    ['plain', command],
    ['reply prefix', `Re: ${command}`],
    ['B encoded', encodedB(command)],
    ['Q encoded', encodedQ(command)],
    ['lowercase encoding and language tag', `=?utf-8*en?q?${command.replace(/ /g, '_')}?=`],
    ['unknown charset ASCII fallback', `=?unknown-charset?Q?${command.replace(/ /g, '=20')}?=`],
    ['folded plain header', command.replace(' role for ', '\r\n\trole for ')],
    ['folded adjacent encoded words', `${encodedB(command.slice(0, 30))}\r\n\t${encodedQ(command.slice(30))}`],
    ['adjacent encoded words', `${encodedQ(command.slice(0, 35))} ${encodedB(command.slice(35))}`],
    ['three adjacent encoded words', `${encodedB(command.slice(0, 20))} ${encodedQ(command.slice(20, 35))} ${encodedB(command.slice(35))}`],
  ])('accepts %s and preserves the original signed subject bytes', async (_, subject) => {
    const raw = buildClaimInboxEmail({ subject });
    const { state } = await fixture.deliver({ raw });
    expect(state.rejections).toEqual([]);
    expect((await (await fixture.fetch()).json()).eml).toBe(inboxBytesToString(raw));
  });

  it.each([
    ['missing', null], ['empty', ''], ['unrelated', 'Hello'],
    ['short address', 'Claim POP role for 0x1234'],
    ['overlong address', `${command}a`], ['nonhex address', `Claim POP role for 0x${'z'.repeat(40)}`],
    ['malformed B', '=?UTF-8?B?%%%?='], ['malformed Q', '=?UTF-8?Q?Claim=ZZPOP?='],
  ])('rejects %s subjects without writing KV', async (_, subject) => {
    const { state } = await fixture.deliver({ raw: buildClaimInboxEmail({ subject }) });
    expect(state.rejections).toEqual([expect.stringContaining('Not a POP role-claim email')]);
    expect(fixture.kv.calls.put).toEqual([]);
  });

  it.each([
    ['missing signature', { dkim: null }],
    ['signature only in body', { dkim: null, body: 'DKIM-Signature: this is body text\r\n' }],
    ['signature text in another header', { dkim: null, extraHeaders: ['X-Comment: DKIM-Signature: not a header'] }],
  ])('rejects %s', async (_, options) => {
    const { state } = await fixture.deliver({ raw: buildClaimInboxEmail(options) });
    expect(state.rejections).toEqual([expect.stringContaining('no DKIM signature')]);
    expect(fixture.kv.calls.put).toEqual([]);
  });

  it('accepts a case-insensitive, folded DKIM header as presence only, without checking its signature', async () => {
    const raw = inboxBytesToString(buildClaimInboxEmail()).replace('DKIM-Signature:', 'dkim-signature:').replace('; s=simulation;', ';\r\n\ts=simulation;');
    const { state } = await fixture.deliver({ raw });
    expect(state.rejections).toEqual([]);
    expect((await fixture.fetch()).status).toBe(200);
  });

  it('distinguishes RFC2047 inbox routing from current circuit command compatibility', async () => {
    const subject = encodedB(command);
    await fixture.deliver({ raw: buildClaimInboxEmail({ subject }) });
    expect((await fixture.fetch()).status).toBe(200);
    // A DKIM signed-header projection retains RFC2047 source bytes. This is a synthetic
    // projection, not a verified signature. The accepted core currently requires a literal command.
    const signed = new TextEncoder().encode(`from:member@example.test\r\nsubject:${subject}\r\n`);
    expect(() => buildCircuitInputHints({
      version: 'v1', emailHeader: [...signed, ...new Array(1024 - signed.length).fill(0)].map(String),
      signedHeaderLength: signed.length, fromEmail: 'member@example.test', dkimDomain: 'example.test', claimer: CLAIM_INBOX_ADDRESS,
    })).toThrow(/bound claim command/);
  });
});

describe('bounded streams and storage failures', () => {
  const sizedEmail = size => {
    const empty = buildClaimInboxEmail({ body: '' });
    const raw = new Uint8Array(size).fill(0x61);
    raw.set(empty);
    return raw;
  };

  it('accepts exactly the configured byte limit', async () => {
    const { message, state } = await fixture.deliver({ raw: sizedEmail(CLAIM_INBOX_MAX_BYTES), chunkSize: 8191 });
    expect(state.rejections).toEqual([]);
    expect(state.cancellations).toEqual([]);
    expect(message.raw.locked).toBe(false);
    expect(fixture.kv.calls.put[0].value).toHaveLength(CLAIM_INBOX_MAX_BYTES);
  });

  it.each([CLAIM_INBOX_MAX_BYTES + 1, 8191])('rejects oversized streams with chunk size %i and cancels immediately', async chunkSize => {
    const { message, state } = await fixture.deliver({ raw: sizedEmail(CLAIM_INBOX_MAX_BYTES + 100_000), chunkSize });
    expect(state.rejections).toEqual(['Message too large.']);
    expect(state.cancellations).toHaveLength(1);
    expect(state.chunksRead).toBe(Math.floor(CLAIM_INBOX_MAX_BYTES / chunkSize) + 1);
    expect(message.raw.locked).toBe(false);
    expect(fixture.kv.calls.put).toEqual([]);
  });

  it('keeps the size rejection even when stream cancellation fails', async () => {
    const { message, state } = await fixture.deliver({ raw: sizedEmail(CLAIM_INBOX_MAX_BYTES + 1), chunkSize: CLAIM_INBOX_MAX_BYTES + 1, cancelError: new Error('Synthetic cancel failure') });
    expect(state.rejections).toEqual(['Message too large.']);
    expect(state.cancellations).toHaveLength(1);
    expect(message.raw.locked).toBe(false);
    expect(fixture.kv.calls.put).toEqual([]);
  });

  it('rejects a read failure without partial storage and releases the stream reader', async () => {
    const { message, state } = await fixture.deliver({ chunkSize: 20, readErrorAtChunk: 2 });
    expect(state.rejections).toEqual(['Could not process message.']);
    expect(message.raw.locked).toBe(false);
    expect(fixture.kv.calls.put).toEqual([]);
  });

  it('rejects KV write failure without exposing its details or replacing the previous mail', async () => {
    const raw = buildClaimInboxEmail();
    await fixture.deliver({ raw });
    fixture.kv.failNext('put', new Error('Private KV diagnostic must not escape'));
    const { state } = await fixture.deliver({ raw: buildClaimInboxEmail({ body: 'Not persisted' }) });
    expect(state.rejections).toEqual(['Could not process message.']);
    expect((await (await fixture.fetch()).json()).eml).toBe(inboxBytesToString(raw));
  });

  it('returns a retryable JSON/CORS response for KV read failure and recovers on the next poll', async () => {
    fixture.kv.failNext('get', new Error('Private KV diagnostic must not escape'));
    const response = await fixture.fetch(undefined, { headers: { Origin: CLAIM_INBOX_ORIGIN } });
    expect(response.status).toBe(503);
    expect(response.headers.get('Access-Control-Allow-Origin')).toBe(CLAIM_INBOX_ORIGIN);
    expect(await response.json()).toEqual({ error: 'Could not load claim email.' });
    expect((await fixture.fetch()).status).toBe(404);
  });
});

describe('HTTP routes, methods, validation and CORS', () => {
  it.each(['', '0x1234', `0x${'g'.repeat(40)}`, `${CLAIM_INBOX_ADDRESS}1`, ` ${CLAIM_INBOX_ADDRESS}`])('rejects invalid claimer %j with 400 before reading KV', async address => {
    const response = await fixture.fetch(pathFor(address));
    expect(response.status).toBe(400);
    expect(await response.json()).toEqual({ error: 'invalid claimer address' });
    expect(fixture.kv.calls.get).toEqual([]);
  });

  it('serves health independently of KV and returns JSON 404 for unknown routes', async () => {
    const health = await fixture.fetch('/health');
    expect(health.status).toBe(200);
    expect(await health.json()).toEqual({ ok: true });
    const missing = await fixture.fetch('/unknown');
    expect(missing.status).toBe(404);
    expect(await missing.json()).toEqual({ error: 'not found' });
    expect(fixture.kv.calls.get).toEqual([]);
  });

  it.each(['/health', '/claim-email'])('rejects unsupported methods at %s without touching KV', async path => {
    for (const method of ['POST', 'PUT', 'DELETE', 'HEAD']) {
      const response = await fixture.fetch(path, { method });
      expect(response.status).toBe(405);
      expect(response.headers.get('Allow')).toBe('GET, OPTIONS');
    }
    expect(fixture.kv.calls.get).toEqual([]);
  });

  it('handles preflight without requiring a valid route or address', async () => {
    const response = await fixture.fetch('/unknown', { method: 'OPTIONS', headers: { Origin: CLAIM_INBOX_ORIGIN } });
    expect(response.status).toBe(200);
    expect(await response.text()).toBe('');
    expect(response.headers.get('Access-Control-Allow-Origin')).toBe(CLAIM_INBOX_ORIGIN);
    expect(response.headers.get('Access-Control-Allow-Methods')).toBe('GET, OPTIONS');
    expect(response.headers.get('Access-Control-Allow-Headers')).toBe('Content-Type');
    expect(response.headers.get('Vary')).toBe('Origin');
    expect(fixture.kv.calls.get).toEqual([]);
  });

  it.each([
    ['*', 'https://unlisted.example.test', '*'],
    [undefined, 'https://unlisted.example.test', '*'],
    [' https://first.example.test, https://app.example.test ', CLAIM_INBOX_ORIGIN, CLAIM_INBOX_ORIGIN],
    [CLAIM_INBOX_ORIGIN, 'https://unlisted.example.test', null],
    [CLAIM_INBOX_ORIGIN, '', null],
  ])('applies configured CORS %j for origin %j', async (allowed, origin, expected) => {
    fixture.env.ALLOWED_ORIGIN = allowed;
    for (const path of ['/health', '/claim-email?claimer=invalid', '/unknown']) {
      const response = await fixture.fetch(path, { headers: origin ? { Origin: origin } : {} });
      expect(response.headers.get('Access-Control-Allow-Origin')).toBe(expected);
      expect(response.headers.get('Vary')).toBe('Origin');
    }
  });
});
